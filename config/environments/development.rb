require "active_support/core_ext/integer/time"

Rails.application.configure do
  # Settings specified here will take precedence over those in config/application.rb.

  # Make code changes take effect immediately without server restart.
  config.enable_reloading = true

  # Do not eager load code on boot.
  config.eager_load = false

  # Show full error reports.
  config.consider_all_requests_local = true

  # Enable server timing.
  config.server_timing = true

  # Enable/disable Action Controller caching. By default Action Controller caching is disabled.
  # Run rails dev:cache to toggle Action Controller caching.
  if Rails.root.join("tmp/caching-dev.txt").exist?
    config.action_controller.perform_caching = true
    config.action_controller.enable_fragment_cache_logging = true
    config.public_file_server.headers = { "cache-control" => "public, max-age=#{2.days.to_i}" }
  else
    config.action_controller.perform_caching = false
  end

  config.hosts << ".ngrok-free.dev"

  # Store uploaded files on the local file system (see config/storage.yml for options).
  # config.active_storage.service = :local

  config.action_mailer.perform_caching = false
  config.action_mailer.default_url_options = { host: ENV["HOST"].sub(%r{^https?://}, "") }
  config.action_mailer.perform_deliveries = true
  config.action_mailer.raise_delivery_errors = true
  if ENV["DEVELOPMENT_SMTP_USER_NAME"].present?
    config.action_mailer.smtp_settings = {
      user_name: ENV["DEVELOPMENT_SMTP_USER_NAME"],
      password: ENV["DEVELOPMENT_SMTP_PASWORD"],
      address: ENV["DEVELOPMENT_SMTP_HOST"],
      domain: ENV["DEVELOPMENT_SMTP_DOMAIN"],
      port: ENV["DEVELOPMENT_SMTP_PORT"],
      authentication: :cram_md5,
    }
  else
    config.action_mailer.delivery_method = :letter_opener_web
  end
  config.action_mailer.asset_host = ENV["HOST"]

  config.active_job.queue_adapter = :good_job
  # config.active_job.queue_adapter = :inline # perform all jobs inline

  config.action_mailer.perform_caching = false

  # allows for individual config with ENV variable
  # note: the Rails default is actually debug rather than info
  config.log_level = ENV.fetch("LOG_LEVEL", :info)

  # to see debug logs when running with foreman or overmind we need to log to STDOUT
  logger = ActiveSupport::Logger.new($stdout)
  logger.formatter = config.log_formatter
  # TaggedLogging fixes an issue for asset requests but I think it is not required anymore
  # cf https://github.com/rails/sprockets-rails/issues/376#issuecomment-287560399
  tagged_logger = ActiveSupport::TaggedLogging.new(logger)
  config.logger = tagged_logger

  # Print deprecation notices to the Rails logger.
  config.active_support.deprecation = :log

  # Raise exceptions for disallowed deprecations.
  config.active_support.disallowed_deprecation = :raise

  # Tell Active Support which deprecation messages to disallow.
  config.active_support.disallowed_deprecation_warnings = []

  # Raise an error on page load if there are pending migrations.
  config.active_record.migration_error = :page_load

  # Highlight code that triggered database queries in logs.
  config.active_record.verbose_query_logs = true

  # Append comments with runtime information tags to SQL queries in logs.
  config.active_record.query_log_tags_enabled = true

  # Highlight code that enqueued background job in logs.
  config.active_job.verbose_enqueue_logs = true

  # Highlight code that triggered redirect in logs.
  config.action_dispatch.verbose_redirect_logs = true

  # en production ces clés sont dans des variables d’environnement
  config.active_record.encryption.primary_key = "rdvsp_ar_primary_key_12345"
  config.active_record.encryption.deterministic_key = "rdvsp_ar_deterministic_key_12345"
  config.active_record.encryption.key_derivation_salt = "rdvsp_ar_key_derivation_salt_12345"

  # Suppress logger output for asset requests.
  config.assets.quiet = true

  # Raises error for missing translations.
  # config.i18n.raise_on_missing_translations = true

  # Annotate rendered view with file names.
  config.action_view.annotate_rendered_view_with_filenames = true

  # Use an evented file watcher to asynchronously detect changes in source code,
  # routes, locales, etc. This feature depends on the listen gem.
  config.file_watcher = ActiveSupport::EventedFileUpdateChecker

  # Check N+1 Queries / Eager loading
  config.after_initialize do
    Bullet.enable = true
    # Bullet.alert = true
    Bullet.rails_logger = true
  end

  # https://github.com/JackC/tod/#activemodel-serializable-attribute-support
  config.active_record.time_zone_aware_types = [:datetime]
  # Uncomment if you wish to allow Action Cable access from any origin.
  # config.action_cable.disable_request_forgery_protection = true

  # Raise error when a before_action's only/except options reference missing actions.
  # config.action_controller.raise_on_missing_callback_actions = true

  # Apply autocorrection by RuboCop to files generated by `bin/rails generate`.
  config.generators.apply_rubocop_autocorrect_after_generate!

  # Ces domaines peuvent être utilisés en local sans modification du /etc/hosts.
  # En effet, Firefox et Chrome font pointer le TLD .localhost vers 127.0.0.1.
  config.hosts << "www.rdv-solidarites.localhost" # http://rdv-solidarites.localhost:3000/
  config.hosts << "www.rdv-aide-numerique.localhost" # http://rdv-aide-numerique.localhost:3000/
  config.hosts << "www.rdv-mairie.localhost" # http://rdv-mairie.localhost:3000/
  config.hosts << "www.rdv-etat.localhost" # http://www.rdv-etat.localhost:3000/

  # Live reload en dev : les changements de vues, helpers, locales et de builds esbuild rechargent la page via Turbo,
  config.hotwire_livereload.skip_listen_paths << Rails.root.join("app/assets/stylesheets") # c'est le build fini qu'on watch pas la source.
  # changement JS : il faut recharger la page car les <script> n'ont pas de data-turbo-track et ne sont pas ré-exécutés par un Turbo.visit
  config.hotwire_livereload.force_reload_paths << Rails.root.join("app/assets/builds/.*\\.js")
end
